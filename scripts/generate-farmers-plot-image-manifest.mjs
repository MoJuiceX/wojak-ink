import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const COLLECTION_ID = 'col10hfq4hml2z0z0wutu3a9hvt60qy9fcq4k4dznsfncey4lu6kpt3su7u9ah';
const COLLECTION_SIZE = 4200;
const PAGE_SIZE = 100;
const API_BASE = `https://api.mintgarden.io/collections/${COLLECTION_ID}/nfts?size=${PAGE_SIZE}&include_metadata=true&include_uris=true`;

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const outputPath = path.resolve(__dirname, '../functions/_data/farmersPlotImageManifest.ts');
const publicDir = path.resolve(__dirname, '../public/assets/farmers-plot-fallbacks');
const localSourceDir = process.env.FARMERS_PLOT_SOURCE_DIR
  ? path.resolve(process.env.FARMERS_PLOT_SOURCE_DIR)
  : path.resolve(process.env.HOME || '', 'Pictures/NFT_Collections/Wojak_NFT/Wojak PFPs/Wojak Farmers Plot final');

function getEditionNumber(item) {
  const direct = Number(item?.edition_number);
  if (Number.isInteger(direct) && direct > 0) return direct;

  const metadataEdition = Number(item?.metadata?.edition_number);
  if (Number.isInteger(metadataEdition) && metadataEdition > 0) return metadataEdition;

  const name = String(item?.name || item?.metadata?.name || '');
  const match = name.match(/#(\d{1,4})/);
  if (!match) return null;

  const parsed = Number(match[1]);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : null;
}

function getStableImageUrl(item) {
  const direct = [item?.thumbnail_uri, item?.preview_uri].find(
    (value) => typeof value === 'string' && value.startsWith('https://')
  );
  if (direct) return direct;

  const dataUri = Array.isArray(item?.data_uris)
    ? item.data_uris.find((value) => typeof value === 'string' && value.startsWith('https://'))
    : null;

  return dataUri || null;
}

async function fetchPage(cursor) {
  const url = cursor ? `${API_BASE}&page=${encodeURIComponent(cursor)}` : API_BASE;
  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(`MintGarden request failed with ${response.status} for ${url}`);
  }

  return response.json();
}

async function main() {
  const manifest = new Map();
  const seenCursors = new Set();
  let cursor = null;

  while (true) {
    if (cursor) {
      if (seenCursors.has(cursor)) {
        throw new Error(`Pagination cursor repeated: ${cursor}`);
      }
      seenCursors.add(cursor);
    }

    const page = await fetchPage(cursor);
    const items = Array.isArray(page?.items) ? page.items : [];

    if (items.length === 0) {
      break;
    }

    for (const item of items) {
      const edition = getEditionNumber(item);
      const imageUrl = getStableImageUrl(item);

      if (!edition) {
        throw new Error(`Unable to resolve edition number for item ${JSON.stringify(item)}`);
      }

      if (!imageUrl) {
        throw new Error(`Missing stable image URL for edition ${edition}`);
      }

      manifest.set(edition, imageUrl);
    }

    if (!page?.next) {
      break;
    }

    cursor = page.next;
  }

  if (manifest.size !== COLLECTION_SIZE) {
    const missingEditions = [];
    for (let edition = 1; edition <= COLLECTION_SIZE; edition += 1) {
      if (!manifest.has(edition)) {
        missingEditions.push(edition);
      }
    }

    await fs.mkdir(publicDir, { recursive: true });

    for (const edition of missingEditions) {
      const localFile = path.join(localSourceDir, `${edition}.png`);

      try {
        await fs.access(localFile);
      } catch {
        continue;
      }

      const publicFile = path.join(publicDir, `${edition}.png`);
      await fs.copyFile(localFile, publicFile);
      manifest.set(edition, `/assets/farmers-plot-fallbacks/${edition}.png`);
    }
  }

  if (manifest.size !== COLLECTION_SIZE) {
    throw new Error(`Expected ${COLLECTION_SIZE} editions, received ${manifest.size}`);
  }

  const sortedEntries = [...manifest.entries()].sort((a, b) => a[0] - b[0]);
  const body = sortedEntries
    .map(([edition, imageUrl]) => `  ${edition}: ${JSON.stringify(imageUrl)},`)
    .join('\n');

  const fileContents = `/**
 * Static edition-to-image manifest for the immutable Wojak Farmers Plot collection.
 *
 * Generated by scripts/generate-farmers-plot-image-manifest.mjs
 */

export const FARMERS_PLOT_IMAGE_BY_EDITION: Record<number, string> = {
${body}
};
`;

  await fs.writeFile(outputPath, fileContents);
  console.log(`Wrote ${manifest.size} image URLs to ${outputPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
